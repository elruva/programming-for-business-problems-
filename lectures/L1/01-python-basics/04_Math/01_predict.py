# Q1: What is the difference between / and //?
# Answer: / gives a decimal, // throws the decimal away and rounds down

# Q2: What does ** do?
# Answer: It raises a number to a power, so 2 ** 4 is 2*2*2*2

# Q3: What does % (modulus) calculate?
# Answer: The remainder, so 5 % 3 leaves 2
