exampleText = "Hello, World!"

print(exampleText[0:5])
print(exampleText[7:12])
print(exampleText[-1])

# Q1: What does [0:5] extract from the string?
# Answer: Hello - characters 0 to 4, so the end number is not included

# Q2: What does [7:12] extract from the string?
# Answer: World - characters 7 to 11

# Q3: What does [-1] mean?
# Answer: The last character, here !
